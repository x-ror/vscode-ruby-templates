//! Lazy translation keys (`t(".title")`) that the default locale of `config/locales` has no entry for, found in the Ruby the
//! template compiles to and mapped back to the template. Only literal lazy keys are checked: an absolute key may come from a
//! gem (`date.formats`, `helpers.submit.create`), a lazy key of a gem's own view from the gem's locale files.

use crate::rails::i18n::{self, Catalog};
use crate::rails::project::Project;
use crate::ruby::generated::Compiled;
use crate::util::{self, edit_distance, LineIndex};
use ruby_prism::{CallNode, Node, Visit};
use std::path::Path;
use tower_lsp_server::ls_types::Diagnostic;

pub(crate) const I18N_MISSING_KEY: &str = "Rails/I18nMissingKey";

const TRANSLATIONS: [&[u8]; 2] = [b"t", b"translate"];
/// Options that make the key resolve somewhere else, or not need an entry.
const REDIRECTING_OPTIONS: [&[u8]; 3] = [b"default", b"scope", b"locale"];
/// A key this many edits from the typed one is offered as the one meant.
const MAX_SUGGESTION_DISTANCE: usize = 2;

/// The findings in `root`, the parse of `compiled`, the Ruby `text` compiles to; `view` is the template's file.
pub(crate) fn diagnostics(
    text: &str,
    view: &Path,
    project: &Project,
    catalog: &Catalog,
    compiled: &Compiled,
    root: &Node,
) -> Vec<Diagnostic> {
    let mut finder = Finder { keys: Vec::new() };
    finder.visit(root);
    let index = LineIndex::new(text);
    finder
        .keys
        .into_iter()
        .filter_map(|(key, start, end)| {
            let full = i18n::full_key(project, view, &key)?;
            let scope = full.strip_suffix(&key)?;
            // A copy of a gem's view reads the gem's translations.
            let owner = full.split('.').next().unwrap_or_default();
            if catalog.has(&full) || project.has_gem_family(owner) {
                return None;
            }
            let (start, end) = compiled.template_span(start, end)?;
            let hint = closest(catalog, scope, &key).map(|near| format!("; did you mean `{near}`?")).unwrap_or_default();
            let message = format!("Translation `{full}` is missing in the `{}` locale{hint}", catalog.default_locale());
            Some(util::coded(util::warning(index.range(start, end), message), I18N_MISSING_KEY))
        })
        .collect()
}

fn closest(catalog: &Catalog, scope: &str, key: &str) -> Option<String> {
    let near = catalog
        .keys_under(scope)
        .into_iter()
        .map(|candidate| (edit_distance(key, candidate), candidate))
        .filter(|&(distance, _)| distance <= MAX_SUGGESTION_DISTANCE && distance < key.chars().count())
        .min_by_key(|&(distance, _)| distance);
    near.map(|(_, candidate)| candidate.to_string())
}

struct Finder {
    /// Each lazy key with the generated bytes of its literal.
    keys: Vec<(String, usize, usize)>,
}

impl<'pr> Visit<'pr> for Finder {
    fn visit_call_node(&mut self, call: &CallNode<'pr>) {
        self.keys.extend(lazy_key(call));
        ruby_prism::visit_call_node(self, call);
    }
}

/// The literal lazy key of `t(".title", count: 2)`; none when an option can send the lookup elsewhere or the options
/// can't be read.
fn lazy_key(call: &CallNode) -> Option<(String, usize, usize)> {
    if call.receiver().is_some() || !TRANSLATIONS.contains(&call.name().as_slice()) {
        return None;
    }
    let mut arguments = call.arguments()?.arguments().iter();
    let first = arguments.next()?;
    let literal = first.as_string_node()?;
    let key = String::from_utf8(literal.unescaped().to_vec()).ok()?;
    let is_lazy = key.starts_with('.') && key.len() > 1 && !key.contains(char::is_whitespace);
    let options_readable = arguments.all(|argument| {
        let Some(options) = argument.as_keyword_hash_node() else { return false };
        options.elements().iter().all(|element| {
            let name = element.as_assoc_node().and_then(|pair| pair.key().as_symbol_node().map(|name| name.unescaped().to_vec()));
            name.is_some_and(|name| !REDIRECTING_OPTIONS.contains(&name.as_slice()))
        })
    });
    let at = literal.location();
    (is_lazy && options_readable).then(|| (key, at.start() as usize, at.end() as usize))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::code_context;
    use crate::lang::TemplateLang::{self, Erb, Haml, Slim};

    const LOCALE: &str = "en:\n  users:\n    index:\n      title: Users\n      stats:\n        one: One\n        other: Many\n      name_html: <b>x</b>\n    form:\n      save: Save\n  layouts:\n    application:\n      menu: Menu\nfr:\n  users:\n    index:\n      only_fr: Seulement\n";

    fn catalog(locale: &str) -> (std::path::PathBuf, std::sync::Arc<Catalog>) {
        static NEXT: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
        let n = NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        let root = std::env::temp_dir().join(format!("rt-missing-key-{}-{n}", std::process::id()));
        util::write_files(&root, &[("config/application.rb", ""), ("config/locales/en.yml", locale)]);
        (root.clone(), i18n::catalog(&Project::unknown(), &root.join("app/views/x.erb")).unwrap())
    }

    /// The flagged text and message of each finding for the view `file` below app/views.
    fn found(lang: TemplateLang, file: &str, text: &str) -> Vec<(String, String)> {
        let (root, catalog) = catalog(LOCALE);
        let compiled = code_context::compiled(lang, text, None, &[]).unwrap();
        let options = ruby_prism::Options::default().build();
        let result = compiled.parse(&options).unwrap();
        let view = root.join("app/views").join(file);
        let found = diagnostics(text, &view, &Project::unknown(), &catalog, &compiled, &result.node());
        let index = LineIndex::new(text);
        let at = |position| (0..=text.len()).find(|&offset| index.position(offset) == position).unwrap();
        std::fs::remove_dir_all(root).unwrap();
        found.into_iter().map(|d| (text[at(d.range.start)..at(d.range.end)].to_string(), d.message)).collect()
    }

    fn flagged(lang: TemplateLang, file: &str, text: &str) -> Vec<String> {
        found(lang, file, text).into_iter().map(|(flagged, _)| flagged).collect()
    }

    #[test]
    fn a_lazy_key_without_an_entry_is_flagged_in_every_language() {
        assert_eq!(
            found(Erb, "users/index.html.erb", "<h1><%= t(\".titel\") %></h1>\n"),
            [("\".titel\"".into(), "Translation `users.index.titel` is missing in the `en` locale; did you mean `.title`?".into())]
        );
        assert_eq!(flagged(Haml, "users/index.html.haml", "%h1= t(\".titel\")\n"), ["\".titel\""]);
        assert_eq!(flagged(Slim, "users/index.html.slim", "h1 = t(\".titel\")\n"), ["\".titel\""]);
        assert_eq!(
            flagged(Erb, "users/index.html.erb", "<%= translate '.nothing' %>\n<%= t \".other\" %>\n"),
            ["'.nothing'", "\".other\""]
        );
        assert_eq!(flagged(Haml, "users/index.html.haml", "= t \".nothing\"\n%p #{t('.x')}\n"), ["\".nothing\"", "'.x'"]);
        assert_eq!(flagged(Slim, "users/index.html.slim", "= t \".nothing\"\np #{t('.x')}\n"), ["\".nothing\"", "'.x'"]);
        // No entry close enough to suggest.
        assert_eq!(
            found(Erb, "users/index.html.erb", "<%= t(\".nothing\") %>\n")[0].1,
            "Translation `users.index.nothing` is missing in the `en` locale"
        );
    }

    #[test]
    fn keys_with_an_entry_in_the_default_locale_are_quiet() {
        let text = "<%= t(\".title\") %><%= t(\".stats\", count: 2) %><%= t(\".name_html\") %><%= t(\".stats.one\") %>\n";
        assert!(flagged(Erb, "users/index.html.erb", text).is_empty());
        assert!(flagged(Haml, "users/index.html.haml", "= t(\".title\")\n").is_empty());
        assert!(flagged(Slim, "users/index.html.slim", "= t(\".title\")\n").is_empty());
        // The view's own path decides: partials lose the underscore, layouts keep their folder.
        assert!(flagged(Erb, "users/_form.html.erb", "<%= t(\".save\") %>\n").is_empty());
        assert!(flagged(Erb, "layouts/application.html.erb", "<%= t(\".menu\") %>\n").is_empty());
        assert_eq!(flagged(Erb, "users/show.html.erb", "<%= t(\".title\") %>\n"), ["\".title\""]);
        // Only the default locale counts.
        assert_eq!(flagged(Erb, "users/index.html.erb", "<%= t(\".only_fr\") %>\n"), ["\".only_fr\""]);
    }

    #[test]
    fn keys_that_are_not_certain_are_quiet() {
        let erb = [
            "<%= t(\"users.index.nothing\") %>",
            "<%= t(:nothing) %>",
            "<%= t(\".nothing\", default: \"x\") %>",
            "<%= t(\".nothing\", scope: :a) %>",
            "<%= t(\".nothing\", locale: :fr) %>",
            "<%= t(\".nothing\", **options) %>",
            "<%= t(\".nothing\", options) %>",
            "<%= t(\".nothing_#{@kind}\") %>",
            "<%= t(\".\") %>",
            "<%= t(key) %>",
            "<%= I18n.t(\".nothing\") %>",
            "<%= helpers.t(\".nothing\") %>",
            "<%= tt(\".nothing\") %>",
        ];
        for line in erb {
            assert!(flagged(Erb, "users/index.html.erb", line).is_empty(), "{line}");
        }
        assert!(flagged(Haml, "users/index.html.haml", "= t(\".nothing\", default: \"x\")\n").is_empty());
        assert!(flagged(Slim, "users/index.html.slim", "= t(\".nothing\", default: \"x\")\n").is_empty());
    }

    #[test]
    fn a_view_named_for_a_gem_reads_the_gems_translations() {
        let lock = "GEM\n  specs:\n    devise (4.9.4)\n";
        let project = Project::from_lockfile(lock);
        let (root, catalog) = catalog(LOCALE);
        let text = "<%= t(\".sign_in\") %>\n";
        let compiled = code_context::compiled(Erb, text, None, &[]).unwrap();
        let options = ruby_prism::Options::default().build();
        let result = compiled.parse(&options).unwrap();
        let run = |view: &str| diagnostics(text, &root.join("app/views").join(view), &project, &catalog, &compiled, &result.node()).len();
        assert_eq!(run("devise/sessions/new.html.erb"), 0);
        assert_eq!(run("users/new.html.erb"), 1);
        std::fs::remove_dir_all(&root).unwrap();
    }
}
