    #[test]
    fn the_fix_for_a_local_removes_its_declaration_and_comma() {
        let fixed = |text: &str, name: &str| {
            let at = text.find(name).unwrap();
            let index = LineIndex::new(text);
            let edit = remove_local_edit(text, index.range(at, at + name.len()), Close::default(), ruby_prism::Version::Latest)?;
            let from = util::position_to_offset(text, edit.range.start)?;
            let to = util::position_to_offset(text, edit.range.end)?;
            Some(format!("{}{}", &text[..from], &text[to..]))
        };
        assert_eq!(fixed("<%# locals: (a:, b: 1) %>", "b").as_deref(), Some("<%# locals: (a:) %>"));
        assert_eq!(fixed("<%# locals: (a:, b: 1) %>", "a").as_deref(), Some("<%# locals: (b: 1) %>"));
        assert_eq!(fixed("<%# locals: (a:, b: f(1, 2), c:) %>", "b").as_deref(), Some("<%# locals: (a:, c:) %>"));
        assert_eq!(fixed("<%# locals: (a:) %>", "a").as_deref(), Some("<%# locals: () %>"));
        assert_eq!(fixed("<%# locals: (a:, **rest) %>", "a").as_deref(), Some("<%# locals: (**rest) %>"));
        assert_eq!(fixed("-# locals: (a:,\n  b:)\n", "b").as_deref(), Some("-# locals: (a:)\n"));
    }
