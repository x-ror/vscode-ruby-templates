//! Calls whose result a view throws away (`<% render "x" %>`, `<% link_to … %>`) and debugging left in one, found in the
//! Ruby the template compiles to and mapped back to the template.

use crate::code_context;
use crate::lang::TemplateLang;
use crate::ruby::generated::{Compiled, IGNORED_ERROR};
use crate::util::{self, LineIndex};
use ruby_prism::{CallNode, Node, StatementsNode, Visit};
use std::collections::BTreeMap;
use tower_lsp_server::ls_types::{Diagnostic, Position, Range, TextEdit};

pub(crate) const SILENT_RENDER: &str = "Rails/SilentRender";
pub(crate) const SILENT_HELPER: &str = "Rails/SilentHelper";
pub(crate) const DEBUG_OUTPUT: &str = "Rails/DebugOutput";

/// Helpers that only return markup or text; calling one where the output is discarded does nothing.
const MARKUP_HELPERS: &[&str] = &[
    "link_to",
    "link_to_if",
    "link_to_unless",
    "link_to_unless_current",
    "button_to",
    "mail_to",
    "image_tag",
    "content_tag",
    "tag",
    "form_with",
    "form_for",
    "form_tag",
    "fields_for",
    "label_tag",
    "text_field_tag",
    "hidden_field_tag",
    "submit_tag",
    "simple_format",
    "number_to_currency",
    "number_to_percentage",
    "number_to_human",
    "number_to_human_size",
    "number_to_phone",
    "number_to_delimiter",
    "number_to_rounded",
    "time_ago_in_words",
    "distance_of_time_in_words",
];

/// `tag.div`, `tag.span`: the builder accepts any name, so only HTML's own are taken for the helper and not for a local `tag`.
const TAG_BUILDER_ELEMENTS: &[&str] = &[
    "a", "article", "aside", "b", "br", "button", "div", "em", "footer", "form", "h1", "h2", "h3", "h4", "h5", "h6", "header", "hr", "i",
    "img", "input", "label", "li", "main", "nav", "ol", "p", "section", "small", "span", "strong", "table", "td", "th", "tr", "ul",
];

/// With arguments: a bare `p` or `debug` could be a method of the view's own.
const DEBUG_CALLS: &[&str] = &["p", "pp", "puts", "debug"];
const DEBUGGER_COMMANDS: &[&str] = &["byebug", "debugger"];
const BINDING_DEBUGGERS: &[&str] = &["irb", "pry"];

/// Iterators whose block's value is dropped, so the last statement of a block is discarded too.
const DISCARDING_ITERATORS: &[&str] =
    &["each", "each_with_index", "each_pair", "each_with_object", "each_slice", "each_cons", "reverse_each", "times", "find_each"];

#[derive(Clone, Copy, PartialEq)]
enum Kind {
    Render,
    Helper,
    Debug,
}

struct Finding {
    kind: Kind,
    /// The call as written, for the message.
    name: String,
    /// Generated bytes, up to the call's block.
    end: usize,
}

pub(crate) fn diagnostics(lang: TemplateLang, text: &str, extra_engines: &[String], ruby: ruby_prism::Version) -> Vec<Diagnostic> {
    let Some(compiled) = code_context::compiled(lang, text, None, extra_engines) else { return Vec::new() };
    let options = ruby_prism::Options::default().version(ruby).build();
    let result = ruby_prism::parse_with_options(compiled.source.as_bytes(), &options);
    if result.errors().any(|e| e.message() != IGNORED_ERROR.as_bytes()) {
        return Vec::new();
    }
    let mut finder = Finder { compiled: &compiled, found: BTreeMap::new() };
    finder.visit(&result.node());
    let index = LineIndex::new(text);
    let marker = match lang {
        TemplateLang::Erb => ("`<% %>`", "`<%=`"),
        _ => ("`-`", "`=`"),
    };
    finder
        .found
        .into_iter()
        .filter_map(|(start, finding)| {
            let (start, end) = compiled.template_span(start, finding.end)?;
            let name = &finding.name;
            let (code, message) = match finding.kind {
                Kind::Render => (SILENT_RENDER, format!("`{name}` in {} outputs nothing; use {}", marker.0, marker.1)),
                Kind::Helper => (SILENT_HELPER, format!("`{name}` returns markup that {} throws away; use {}", marker.0, marker.1)),
                Kind::Debug => (DEBUG_OUTPUT, format!("`{name}` is debugging left in the view")),
            };
            Some(util::coded(util::warning(index.range(start, end), message), code))
        })
        .collect()
}

/// The edit that makes the silent tag around the call at `start` an output tag: `<%` to `<%=`, `-` to `=`; none when other
/// code comes before the call in its tag.
pub(crate) fn output_marker_edit(lang: TemplateLang, text: &str, start: Position) -> Option<TextEdit> {
    let (line_start, line, column) = util::line_at(text, start);
    let index = LineIndex::new(text);
    if lang == TemplateLang::Erb {
        let call = line_start + column;
        let after_open = text[..call].rfind("<%")? + 2;
        let at = index.position(after_open);
        return text[after_open..call].trim().is_empty().then(|| TextEdit::new(Range::new(at, at), "=".into()));
    }
    let before = &line[..column];
    let marker = line_start + before.rfind('-').filter(|_| before.trim() == "-")?;
    Some(TextEdit::new(index.range(marker, marker + 1), "=".into()))
}

struct Finder<'a> {
    compiled: &'a Compiled,
    /// By start in the generated source.
    found: BTreeMap<usize, Finding>,
}

impl Finder<'_> {
    /// `used`: the value of the statement may be read by the code around it.
    fn statements(&mut self, node: &StatementsNode, used: bool) {
        let body: Vec<Node> = node.body().iter().collect();
        for (i, statement) in body.iter().enumerate() {
            self.statement(statement, used && i + 1 == body.len());
        }
    }

    fn statement(&mut self, node: &Node, used: bool) {
        if let Some(call) = node.as_call_node() {
            self.record_statement(&call, used);
            self.call(&call, used);
        } else if let Some(branch) = node.as_if_node() {
            self.visit(&branch.predicate());
            branch.statements().inspect(|body| self.statements(body, used));
            branch.subsequent().inspect(|next| self.statement(next, used));
        } else if let Some(branch) = node.as_unless_node() {
            self.visit(&branch.predicate());
            branch.statements().inspect(|body| self.statements(body, used));
            branch.else_clause().inspect(|clause| branch_else(self, clause, used));
        } else if let Some(clause) = node.as_else_node() {
            branch_else(self, &clause, used);
        } else {
            self.visit(node);
        }
    }

    /// Visits a call; the block of a discarded iterator is the one block whose last value is dropped.
    fn call(&mut self, call: &CallNode, used: bool) {
        let block = call.block().and_then(|block| block.as_block_node());
        let discarding = !used && DISCARDING_ITERATORS.contains(&String::from_utf8_lossy(call.name().as_slice()).as_ref());
        let Some(body) = block.as_ref().filter(|_| discarding).and_then(|block| block.body()).and_then(|body| body.as_statements_node())
        else {
            return self.visit_call_node(call);
        };
        call.receiver().inspect(|receiver| self.visit(receiver));
        call.arguments().inspect(|arguments| self.visit_arguments_node(arguments));
        self.statements(&body, false);
    }

    fn record_statement(&mut self, call: &CallNode, used: bool) {
        match classify(call) {
            Some((Kind::Debug, name)) => self.record(call, Kind::Debug, name),
            Some((kind, name)) if !used => self.record(call, kind, name),
            _ => {}
        }
    }

    fn record(&mut self, call: &CallNode, kind: Kind, name: String) {
        let start = call.location().start() as usize;
        let end = call.block().map_or(call.location().end(), |block| block.location().start()) as usize;
        let end = start + self.compiled.source[start..end].trim_end().len();
        self.found.entry(start).or_insert(Finding { kind, name, end });
    }
}

fn branch_else(finder: &mut Finder, clause: &ruby_prism::ElseNode, used: bool) {
    clause.statements().inspect(|body| finder.statements(body, used));
}

impl<'pr> Visit<'pr> for Finder<'_> {
    fn visit_statements_node(&mut self, node: &StatementsNode<'pr>) {
        self.statements(node, true);
    }

    /// The call is the whole code of its tag: `<%= debug @user %>` is output, yet it is the debugging.
    fn visit_call_node(&mut self, node: &CallNode<'pr>) {
        let (start, end) = (node.location().start() as usize, node.location().end() as usize);
        if let Some((Kind::Debug, name)) = classify(node).filter(|_| self.compiled.fills_run(start, end)) {
            self.record(node, Kind::Debug, name);
        }
        ruby_prism::visit_call_node(self, node);
    }
}

fn name_of(call: &CallNode) -> String {
    String::from_utf8_lossy(call.name().as_slice()).into_owned()
}

/// What the call is, and how it is written, when it is a call this module knows by name.
fn classify(call: &CallNode) -> Option<(Kind, String)> {
    let name = name_of(call);
    let has_arguments = call.arguments().is_some();
    let Some(receiver) = call.receiver() else {
        let kind = match name.as_str() {
            "render" if has_arguments => Kind::Render,
            _ if has_arguments && MARKUP_HELPERS.contains(&name.as_str()) => Kind::Helper,
            _ if has_arguments && DEBUG_CALLS.contains(&name.as_str()) => Kind::Debug,
            _ if call.is_variable_call() && DEBUGGER_COMMANDS.contains(&name.as_str()) => Kind::Debug,
            _ => return None,
        };
        return Some((kind, name));
    };
    let receiver = receiver.as_call_node().filter(|r| r.receiver().is_none() && r.is_variable_call())?;
    let receiver_name = name_of(&receiver);
    match receiver_name.as_str() {
        "tag" if TAG_BUILDER_ELEMENTS.contains(&name.as_str()) => Some((Kind::Helper, format!("tag.{name}"))),
        "binding" if BINDING_DEBUGGERS.contains(&name.as_str()) && !has_arguments => Some((Kind::Debug, format!("binding.{name}"))),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// (code, flagged text) of each finding.
    fn found(lang: TemplateLang, text: &str) -> Vec<(String, String)> {
        let index = LineIndex::new(text);
        let at = |position| (0..=text.len()).find(|&offset| index.position(offset) == position).unwrap();
        diagnostics(lang, text, &[], ruby_prism::Version::Latest)
            .into_iter()
            .map(|d| (util::code(&d).unwrap().to_string(), text[at(d.range.start)..at(d.range.end)].to_string()))
            .collect()
    }

    fn one(code: &str, flagged: &str) -> Vec<(String, String)> {
        vec![(code.into(), flagged.into())]
    }

    #[test]
    fn silent_calls_in_every_language() {
        use TemplateLang::{Erb, Haml, Slim};
        assert_eq!(found(Erb, "<% render \"x\", a: 1 %>\n"), one(SILENT_RENDER, "render \"x\", a: 1"));
        assert_eq!(found(Haml, "- render \"x\"\n"), one(SILENT_RENDER, "render \"x\""));
        assert_eq!(found(Slim, "- render \"x\"\n"), one(SILENT_RENDER, "render \"x\""));
        assert_eq!(found(Erb, "<% link_to \"Home\", root_path %>\n"), one(SILENT_HELPER, "link_to \"Home\", root_path"));
        assert_eq!(found(Haml, "%p\n  - image_tag \"a.png\"\n"), one(SILENT_HELPER, "image_tag \"a.png\""));
        assert_eq!(found(Slim, "p\n  - tag.span \"x\"\n"), one(SILENT_HELPER, "tag.span \"x\""));
        assert_eq!(found(Erb, "<% tag.div class: \"a\" do %>x<% end %>\n"), one(SILENT_HELPER, "tag.div class: \"a\""));
    }

    #[test]
    fn block_forms_are_flagged_up_to_the_block() {
        assert_eq!(found(TemplateLang::Erb, "<% render layout: \"x\" do %>y<% end %>\n"), one(SILENT_RENDER, "render layout: \"x\""));
        assert_eq!(found(TemplateLang::Erb, "<% link_to root_path do %>y<% end %>\n"), one(SILENT_HELPER, "link_to root_path"));
        assert_eq!(found(TemplateLang::Haml, "- link_to root_path do\n  y\n"), one(SILENT_HELPER, "link_to root_path"));
        assert_eq!(found(TemplateLang::Slim, "- render layout: \"x\" do\n  | y\n"), one(SILENT_RENDER, "render layout: \"x\""));
    }

    #[test]
    fn silent_calls_in_conditions_and_loops() {
        let erb =
            "<% if a %>\n<% render \"x\" %>\n<% end %>\n<% render \"y\" if b %>\n<% items.each do |i| %>\n<% render i %>\n<% end %>\n";
        assert_eq!(found(TemplateLang::Erb, erb).len(), 3);
        assert_eq!(found(TemplateLang::Haml, "- items.each do |i|\n  - render i\n").len(), 1);
        assert_eq!(found(TemplateLang::Slim, "- items.each do |i|\n  - render i\n").len(), 1);
    }

    #[test]
    fn calls_whose_value_is_used_are_not_flagged() {
        use TemplateLang::{Erb, Haml, Slim};
        let none: Vec<(String, String)> = Vec::new();
        for text in [
            "<%= render \"x\" %>",
            "<% x = render \"x\" %>",
            "<% y = link_to \"a\", b %>",
            "<%= link_to \"a\", b %>",
            "<% foo(render(\"x\")) %>",
            "<% foo render(\"x\") %>",
            "<%= foo do %><% render \"x\" %><% end %>",
            "<% content_for :a do %><% render \"x\" %><% end %>",
            "<% cond && render(\"x\") %>",
            "<% form.fields_for :a do |f| %><% end %>",
            "<% content_for :a, link_to(\"x\", y) %>",
            "<% provide :a, tag.div %>",
            "<% helpers.link_to \"a\", b %>",
            "<% render %>",
            "<% link_to %>",
            "<% tag.foo \"x\" %>",
            "<% tag %>",
            "<%# render \"x\" %>",
            "<%= foo.render \"x\" %>",
        ] {
            assert_eq!(found(Erb, text), none, "{text}");
        }
        for text in [
            "= render \"x\"\n",
            "- x = render \"x\"\n",
            "%p= link_to \"a\", b\n",
            "- items.map do |i|\n  - render i\n",
            "= foo do\n  - render \"x\"\n",
        ] {
            assert_eq!(found(Haml, text), none, "{text}");
        }
        for text in ["= render \"x\"\n", "p = link_to \"a\", b\n", "- x = render \"x\"\n"] {
            assert_eq!(found(Slim, text), none, "{text}");
        }
    }

    #[test]
    fn debugging_is_flagged_as_output_or_statement() {
        use TemplateLang::{Erb, Haml, Slim};
        let debug = |text: &str| DEBUG_OUTPUT.to_string() + "|" + text;
        let codes = |lang, text: &str| found(lang, text).into_iter().map(|(code, text)| code + "|" + &text).collect::<Vec<_>>();
        assert_eq!(
            codes(Erb, "<%= debug @user %>\n<% binding.irb %><% binding.pry %>\n"),
            [debug("debug @user"), debug("binding.irb"), debug("binding.pry")]
        );
        assert_eq!(codes(Erb, "<% p @a %><%= pp @a %><% puts \"x\" %><% byebug %><% debugger %>\n").len(), 5);
        assert_eq!(codes(Haml, "= debug @user\n- binding.irb\n%p= p(@a)\n"), [debug("debug @user"), debug("binding.irb"), debug("p(@a)")]);
        assert_eq!(
            codes(Slim, "= debug @user\n- binding.pry\np = puts(@a)\n"),
            [debug("debug @user"), debug("binding.pry"), debug("puts(@a)")]
        );
    }

    #[test]
    fn names_that_are_not_debugging_are_left_alone() {
        use TemplateLang::{Erb, Haml, Slim};
        let none: Vec<(String, String)> = Vec::new();
        for text in [
            "<% p = 1 %><%= p %>",
            "<%= p.name %>",
            "<%= p %>",
            "<%= form.p %>",
            "<%= obj.debug %>",
            "<%= obj.debug @a %>",
            "<%= foo(debug(@a)) %>",
            "<%= debug %>",
            "<% x = pp(@a) %>",
            "<% debugger = 1 %><%= debugger %>",
            "<% [1].each do |byebug| %><% byebug %><% end %>",
            "<%= binding.local_variable_get(:a) %>",
            "<%= binding.irb(1) %>",
            "<%= puts_all @a %>",
            "<%# binding.irb %>",
            "<%= \"binding.irb\" %>",
        ] {
            assert_eq!(found(Erb, text), none, "{text}");
        }
        assert_eq!(found(Haml, "- p = 1\n= p\n%p= p.name\n"), none);
        assert_eq!(found(Slim, "- p = 1\n= p\np = p.name\n"), none);
    }

    #[test]
    fn templates_with_ruby_errors_get_no_findings() {
        assert!(found(TemplateLang::Erb, "<% render \"x\" %><% if %>\n").is_empty());
    }

    #[test]
    fn the_fix_turns_the_tag_into_an_output_tag() {
        let fixed = |lang, text: &str, flagged: &str| {
            let offset = text.find(flagged).unwrap();
            let edit = output_marker_edit(lang, text, LineIndex::new(text).position(offset))?;
            let index = LineIndex::new(text);
            let (start, end) = (0..=text.len())
                .filter(|&at| index.position(at) == edit.range.start || index.position(at) == edit.range.end)
                .fold((usize::MAX, 0), |(lo, hi), at| (lo.min(at), hi.max(at)));
            Some(format!("{}{}{}", &text[..start], edit.new_text, &text[end..]))
        };
        assert_eq!(fixed(TemplateLang::Erb, "<p>\n<%  render \"x\" -%>\n", "render").as_deref(), Some("<p>\n<%=  render \"x\" -%>\n"));
        assert_eq!(fixed(TemplateLang::Erb, "<% a; render \"x\" %>", "render"), None);
        assert_eq!(fixed(TemplateLang::Haml, "%p\n  - render \"x\"\n", "render").as_deref(), Some("%p\n  = render \"x\"\n"));
        assert_eq!(fixed(TemplateLang::Slim, "- render \"x\"\n", "render").as_deref(), Some("= render \"x\"\n"));
        assert_eq!(fixed(TemplateLang::Slim, "- a; render \"x\"\n", "render"), None);
    }
}
