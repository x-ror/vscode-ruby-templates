//! Ruby generated from a template, and the way back from its errors to the template's lines.

use crate::prism;
use crate::util::{error, leading_ws, span_range, LineIndex};
use tower_lsp::lsp_types::{Diagnostic, Range};

/// Slim and Haml compile into a method body, where `yield` is valid; Prism, parsing it alone, says otherwise.
const IGNORED_ERROR: &str = "Invalid yield";

/// Generated Ruby, and where each of its lines and verbatim runs of code came from.
pub(crate) struct Compiled {
    pub source: String,
    /// The bytes at the start that are no template's: a wrapper whose errors are reported elsewhere.
    pub wrapper_len: usize,
    /// The template line each generated line holds.
    line_of: Vec<Option<usize>>,
    /// Verbatim runs: generated byte range, and the template offset of the first byte; in source order, never
    /// overlapping, which `template_range` searches by.
    verbatim: Vec<(usize, usize, usize)>,
}

impl Compiled {
    pub fn new() -> Self {
        Compiled { source: String::new(), wrapper_len: 0, line_of: vec![None], verbatim: Vec::new() }
    }

    /// Appends text that starts on template line `line`; each of its own lines is the next template line.
    pub fn push(&mut self, text: &str, line: usize) {
        self.push_at(text, Some(line));
    }

    /// Appends text that is on no template line of its own: if it opens a generated line, that line is the one after the
    /// line before it.
    pub fn push_floating(&mut self, text: &str) {
        self.push_at(text, None);
    }

    fn push_at(&mut self, text: &str, line: Option<usize>) {
        for (i, part) in text.split('\n').enumerate() {
            if i > 0 {
                self.new_line();
            }
            if let (Some(slot), Some(line)) = (self.line_of.last_mut().filter(|slot| slot.is_none()), line) {
                *slot = Some(line.saturating_add(i));
            }
            self.source.push_str(part);
        }
    }

    /// A line break that holds no template line of its own.
    pub fn new_line(&mut self) {
        self.source.push('\n');
        self.line_of.push(None);
    }

    /// Remembers that the `len` bytes written from `from` are the template's, starting at `offset`.
    pub fn mark_verbatim(&mut self, from: usize, len: usize, offset: usize) {
        debug_assert!(self.verbatim.last().is_none_or(|&(_, to, _)| to <= from), "verbatim runs out of order");
        self.verbatim.push((from, from + len, offset));
    }

    /// The template byte ranges where the local `name` is read or assigned, among the code the template wrote.
    pub fn local_uses(&self, name: &str) -> prism::LocalUses {
        let uses = prism::local_uses(&self.source, name);
        let spans = uses.spans.into_iter().filter_map(|(start, end)| template_span(&self.verbatim, start, end)).collect();
        prism::LocalUses { spans, ..uses }
    }

    /// Where the template declares the local variable at `template_offset`, within the code the template wrote.
    pub fn local_definition(&self, template_offset: usize) -> Option<(usize, usize)> {
        let (start, end) = prism::local_definition(&self.source, generated_offset(&self.verbatim, template_offset)?)?;
        template_span(&self.verbatim, start, end)
    }

    pub fn block_locals(&self, template_offset: usize) -> Vec<String> {
        generated_offset(&self.verbatim, template_offset).map_or_else(Vec::new, |at| prism::block_locals(&self.source, at))
    }

    /// Prism's errors in the source, at their place in `text`, the template.
    pub fn diagnostics(&self, text: &str, ruby: ruby_prism::Version) -> Vec<Diagnostic> {
        let index = LineIndex::new(text);
        let last = index.line_count().saturating_sub(1);
        prism::syntax_errors(&self.source, ruby)
            .into_iter()
            .filter(|e| e.message != IGNORED_ERROR && e.start >= self.wrapper_len)
            .map(|e| error(self.template_range(&index, last, e.start, e.end, e.range), e.message))
            .collect()
    }

    /// The template range of a generated one: exact inside verbatim code, else the whole content of its line.
    fn template_range(&self, index: &LineIndex, last: usize, start: usize, end: usize, generated: Range) -> Range {
        // Runs are pushed in source order: the first that ends at or after `start` is the first that holds it.
        let run = self.verbatim.get(self.verbatim.partition_point(|&(_, to, _)| to < start)).filter(|&&(from, _, _)| from <= start);
        if let Some(&(from, to, at)) = run {
            return Range::new(index.position(at + start - from), index.position(at + end.min(to) - from));
        }
        let generated_line = generated.start.line as usize;
        let mut line = self.line_of.get(generated_line).copied().flatten();
        if line.is_none() {
            // A line nothing was written on is a blank one: the one after the nearest line before it that has a home.
            let before = self.line_of[..generated_line.min(self.line_of.len())].iter().rposition(Option::is_some);
            line = before.map(|b| self.line_of[b].unwrap_or(0).saturating_add(generated_line - b));
        }
        let line = line.unwrap_or(0).min(last);
        let raw = index.line(line);
        span_range(line, raw, leading_ws(raw).len(), raw.trim_end().len())
    }
}

/// The template range of the generated range `start..end`, when one verbatim run holds all of it.
pub(crate) fn template_span(verbatim: &[(usize, usize, usize)], start: usize, end: usize) -> Option<(usize, usize)> {
    verbatim.iter().find(|&&(from, to, _)| from <= start && end <= to).map(|&(from, _, at)| (at + start - from, at + end - from))
}

/// Where template offset `template` went in the generated source, if it is inside, or just after, verbatim code.
pub(crate) fn generated_offset(verbatim: &[(usize, usize, usize)], template: usize) -> Option<usize> {
    verbatim.iter().find(|&&(from, to, at)| at <= template && template <= at + (to - from)).map(|&(from, _, at)| from + template - at)
}

/// The body of a Ruby double-quoted literal for `text`, as `String#inspect` writes it.
pub(crate) fn ruby_string_body(text: &str) -> String {
    let mut out = String::new();
    push_ruby_string_body(&mut out, text);
    out
}

pub(crate) fn push_ruby_string_body(out: &mut String, text: &str) {
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '"' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            '#' if matches!(chars.peek(), Some('{' | '$' | '@')) => out.push_str("\\#"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c => out.push(c),
        }
    }
}
