/// Every attribute name for completion: `ATTRIBUTES`, then the `data-` and `aria-` ones, then `stimulus`, the attributes
/// the element's Stimulus controllers read.
pub fn attribute_names(stimulus: Vec<String>) -> impl Iterator<Item = String> {
    let data = DATA_KEYS.iter().map(|key| format!("data-{}", key.replace('_', "-")));
    let aria = ARIA_KEYS.iter().map(|key| format!("aria-{key}"));
    ATTRIBUTES.iter().map(|name| name.to_string()).chain(data).chain(aria).chain(stimulus)
}
